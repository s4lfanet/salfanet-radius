// Check batch code epoch vs createdAt
const batchEpoch = 1788141996996;
const createdAt = new Date('2026-08-31T02:06:37.346Z');

console.log('Batch epoch:', batchEpoch);
console.log('As date (UTC):', new Date(batchEpoch).toISOString());
console.log('As date (WIB):', new Date(batchEpoch).toLocaleString('en-US', {timeZone: 'Asia/Jakarta'}));
console.log('');
console.log('DB createdAt:', createdAt.toISOString());
console.log('DB createdAt (WIB):', createdAt.toLocaleString('en-US', {timeZone: 'Asia/Jakarta'}));
console.log('');
console.log('Diff (batch - db):', batchEpoch - createdAt.getTime(), 'ms');

// If batch epoch was generated by Date.now() at creation time,
// and it's 1788141996996, that's 2026-08-31 09:06:36 UTC = 16:06:36 WIB
// But DB says 2026-08-31 02:06:37 UTC = 09:06:37 WIB
// Diff is ~7 hours — this means createdAt was stored as WIB-as-UTC!

console.log('');
console.log('If batch epoch is true UTC (Date.now()):');
console.log('  Batch created at:', new Date(batchEpoch).toISOString(), 'UTC');
console.log('  =', new Date(batchEpoch).toLocaleString('en-US', {timeZone: 'Asia/Jakarta'}), 'WIB');
console.log('  DB createdAt:', createdAt.toISOString(), 'UTC');
console.log('  DB createdAt =', createdAt.toLocaleString('en-US', {timeZone: 'Asia/Jakarta'}), 'WIB');
console.log('  Diff:', (batchEpoch - createdAt.getTime()) / 3600000, 'hours');
